export const LanguageContext = createContext({
  language: "fr",
  t: (key) => key,
  switchLanguage: () => {},
  formatDate: () => {},
  formatNumber: () => {},
  availableLanguages: ["fr", "en"],
});

export const LanguageProvider = ({ children }) => {
  const [language, setLanguage] = useState("fr");
  const [fallbackLanguage] = useState("en");

  useEffect(() => {
    const savedLang = localStorage.getItem("language") || "fr";
    setLanguage(savedLang);
    document.documentElement.lang = savedLang;
  }, []);

  const t = (key, params = {}) => {
    let translation =
      translations[language]?.[key] ||
      translations[fallbackLanguage][key] ||
      key;

    Object.entries(params).forEach(([paramKey, value]) => {
      translation = translation.replace(`{${paramKey}}}`, value);
    });

    return translation;
  };

  const switchLanguage = (newLang) => {
    if (!translations[newLang]) return;
    localStorage.setItem("language", newLang);
    setLanguage(newLang);
    document.documentElement.lang = newLang;
  };

  const formatDate = (date, options = {}) => {
    try {
      return new Intl.DateTimeFormat(language, options).format(new Date(date));
    } catch {
      return new Intl.DateTimeFormat(fallbackLanguage, options).format(
        new Date(date)
      );
    }
  };

  const formatNumber = (number, options = {}) => {
    try {
      return new Intl.NumberFormat(language, options).format(number);
    } catch {
      return new Intl.NumberFormat(fallbackLanguage, options).format(number);
    }
  };

  return (
    <LanguageContext.Provider
      value={{
        language,
        t,
        switchLanguage,
        formatDate,
        formatNumber,
        availableLanguages: Object.keys(translations),
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};
